-- Kora weapon items, ammunition and attachments loaded by kora_core at boot.
local function weapon(name, label, ammotype, weight, weapontype, image)
    return {
        name = name,
        label = label,
        ammotype = ammotype,
        weight = weight,
        type = 'weapon',
        weapontype = weapontype,
        unique = true,
        useable = true,
        image = image or name .. '.webp',
        shouldClose = true,
    }
end

local function ammo(name, label, ammoType, weight, rounds, image, options)
    return {
        name = name,
        label = label,
        weight = weight,
        type = 'item',
        shouldClose = true,
        description = ('%d-round %s.'):format(rounds, label:lower()),
        ammoType = ammoType,
        rounds = rounds,
        image = image,
        gridWidth = options and options.gridWidth,
        gridHeight = options and options.gridHeight,
    }
end

local function item(name, label, weight, image, unique, useable, shouldClose, description, options)
    if shouldClose == nil then
        shouldClose = true
    end
    return {
        name = name,
        label = label,
        weight = weight,
        type = 'item',
        image = image,
        unique = unique or nil,
        useable = useable or nil,
        shouldClose = shouldClose,
        gridWidth = options and options.gridWidth,
        gridHeight = options and options.gridHeight,
        description = description or ''
    }
end


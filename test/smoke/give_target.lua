local H = dofile('test/harness.lua')
local file = assert(io.open('client/give_target.lua', 'r'))
local source = file:read('*a')
file:close()

H.ok(source:find('QB.closest.player', 1, true), 'checks qblib closest player first')
H.ok(source:find("QB.world.getNearbyEntities('player'", 1, true), 'only uses world scan to distinguish multiple recipients')
H.ok(source:find("'qbinventory:ui:giveAvailability'", 1, true), 'browser bridge receives availability only')
H.ok(source:find('Wait(750)', 1, true), 'give availability is refreshed while a session remains open')
H.ok(source:find("'qbinventory:client:giveTargetResolved'", 1, true), 'resolved recipient stays in the local client transport')
H.ok(source:find("exports.qbtarget:addEntity", 1, true), 'multiple recipients require an in-world target selection')
H.ok(source:find("exports.qbtarget:removeEntity", 1, true), 'temporary target registration is cleaned up')
H.ok(source:find("'qbinventory:ui:giveTargeting'", 1, true), 'bridge owns the focus transition for targeting')
H.ok(not source:find('SendNUIMessage', 1, true), 'resolver has no NUI authority')
H.ok(not source:find('SetNuiFocus', 1, true), 'resolver has no focus authority')
H.ok(not source:find('TriggerServerEvent', 1, true), 'resolver has no server authority')
H.finish()

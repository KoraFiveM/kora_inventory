local H = dofile('test/harness.lua')
local function read(path)
    local file = assert(io.open(path, 'r'))
    local source = file:read('*a')
    file:close()
    return source
end

local source = read('server/persistence.lua')
local schema = read('sql/001_secondary_inventories.sql')
local manifest = read('fxmanifest.lua')

H.ok(source:find('inventory.persistence = persistence', 1, true), 'persistence is exposed to server authority')
H.ok(source:find("inv.type == 'player'", 1, true), 'player inventories are excluded')
H.ok(source:find('persistTemporary', 1, true), 'temporary inventory durability is explicit')
H.ok(not source:find('INSERT INTO `players`', 1, true) and not source:find('UPDATE `players`', 1, true), 'secondary persistence never writes qbcore player column')
H.ok(source:find('persistence.normaliseItems', 1, true), 'legacy item normaliser exists')
H.ok(source:find('persistence.markDirty', 1, true) and source:find('persistence.flush', 1, true), 'secondary writes are queued and flushed')
H.ok(source:find('qbinventory:server:migrationProgress', 1, true), 'migration emits progress')
H.ok(source:find("qbinventory-migrate", 1, true), 'migration command exists')
H.ok(source:find("dry-run|run|retry|verify", 1, true), 'all migration operations documented in command')
H.ok(source:find('qbinventory_quarantine', 1, true), 'malformed records quarantine safely')
H.ok(source:find("old.status == 'imported'", 1, true), 'completed imports are idempotent')
H.ok(source:find('not opts.retry', 1, true), 'failed imports require explicit retry')
H.ok(source:find('INFORMATION_SCHEMA', 1, true), 'legacy tables are discovered defensively')
H.ok(schema:find('qbinventory_inventories', 1, true), 'secondary inventory schema exists')
H.ok(schema:find('qbinventory_shop_stock', 1, true), 'shop stock schema exists')
H.ok(schema:find('qbinventory_audit', 1, true), 'audit schema exists')
H.ok(schema:find('qbinventory_migration_state', 1, true), 'migration state schema exists')
H.ok(schema:find('qbinventory_migration_rows', 1, true), 'idempotency schema exists')
H.ok(schema:find('qbinventory_quarantine', 1, true), 'quarantine schema exists')
H.ok(manifest:find("'server/persistence.lua'", 1, true), 'persistence loads before authority')
H.finish()
